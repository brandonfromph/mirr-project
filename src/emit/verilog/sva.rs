/// Check if the registry declares an input signal named `rst_n`.
pub(super) fn module_has_rst_n(registry: &crate::ecs::Registry) -> bool {
    let top_module_id = registry.kinds.iter().enumerate().rev().find_map(|(i, k)| {
        if let Some(crate::ecs::components::KindComponent(crate::ecs::EntityKind::MODULE)) = k {
            Some(crate::ecs::EntityId(i as u32))
        } else {
            None
        }
    });

    for i in 0..registry.names.len() {
        if let Some(top_id) = top_module_id {
            if let Some(crate::ecs::components::ModuleComponent(parent_id)) = &registry.modules[i] {
                if *parent_id != top_id {
                    continue;
                }
            } else {
                continue;
            }
        }

        if let (Some(name_comp), Some(kind_comp)) = (&registry.names[i], &registry.kinds[i]) {
            let sname = registry.resolve_name(name_comp.0);
            if sname == "rst_n" {
                if let crate::ecs::EntityKind::SIGNAL(SignalKind::Input) = kind_comp.0 {
                    return true;
                }
            }
        }
    }
    false
}

/// Emit SVA assertion blocks for all property declarations.
pub(super) fn emit_property_assertions(
    registry: &crate::ecs::Registry,
    has_rst_n: bool,
    sync_map: &std::collections::HashMap<String, String>,
    ft: &FileTable,
    out: &mut String,
) {
    let top_module_id = registry.kinds.iter().enumerate().rev().find_map(|(i, k)| {
        if let Some(crate::ecs::components::KindComponent(crate::ecs::EntityKind::MODULE)) = k {
            Some(crate::ecs::EntityId(i as u32))
        } else {
            None
        }
    });

    let mut has_properties = false;
    for i in 0..registry.names.len() {
        if let Some(top_id) = top_module_id {
            if let Some(crate::ecs::components::ModuleComponent(parent_id)) = &registry.modules[i] {
                if *parent_id != top_id {
                    continue;
                }
            } else {
                continue;
            }
        }

        if let Some(crate::ecs::components::KindComponent(crate::ecs::EntityKind::PROPERTY)) =
            registry.kinds[i]
        {
            has_properties = true;
            break;
        }
    }

    if !has_properties {
        return;
    }

    out.push_str("  // ── Safety Properties (SVA) ──\n\n");

    if has_rst_n {
        out.push_str("  // Enforce reset sequence for formal verification\n");
        out.push_str("  reg f_past_valid = 0;\n");
        out.push_str("  always_ff @(posedge clk) begin\n");
        out.push_str("    f_past_valid <= 1;\n");
        out.push_str("  end\n");
        out.push_str("  always_comb begin\n");
        out.push_str("    if (!f_past_valid) assume (!rst_n);\n");
        out.push_str("  end\n\n");
    }

    for i in 0..registry.names.len() {
        if let Some(top_id) = top_module_id {
            if let Some(crate::ecs::components::ModuleComponent(parent_id)) = &registry.modules[i] {
                if *parent_id != top_id {
                    continue;
                }
            } else {
                continue;
            }
        }

        if let (Some(nc), Some(kind_comp), Some(prop_comp)) =
            (registry.names[i], &registry.kinds[i], &registry.property_comps[i])
        {
            if let crate::ecs::EntityKind::PROPERTY = kind_comp.0 {
                let name = registry.resolve_name(nc.0);
                let span = registry.spans[i].as_ref().map(|s| &s.0);

                let mut clock_domain = "clk";
                if let Some(tc) = &registry.types[i] {
                    if let Some(cd) = tc.0.annotations.clock_domain.as_deref() {
                        clock_domain = cd;
                    }
                }

                emit_single_property(
                    name,
                    prop_comp,
                    clock_domain,
                    has_rst_n,
                    registry,
                    sync_map,
                    ft,
                    out,
                    span,
                );
            }
        }
    }
}

/// Emit a single SVA `assert property` statement.
#[allow(clippy::too_many_arguments)]
pub(super) fn emit_single_property(
    prop_name: &str,
    prop: &crate::ecs::components::PropertyComponent,
    clock: &str,
    has_rst_n: bool,
    registry: &crate::ecs::Registry,
    sync_map: &std::collections::HashMap<String, String>,
    ft: &FileTable,
    out: &mut String,
    span: Option<&Span>,
) {
    emit_source_comment(span, ft, out);
    if let Some(ref origin) = prop.origin {
        out.push_str(&format!("  // Pattern: {origin}\n"));
    }
    out.push_str(&format!("  // property: {}\n", prop_name));

    let sva_keyword = match prop.directive {
        PropertyDirective::Assert => "assert",
        PropertyDirective::Cover => "cover",
        PropertyDirective::Assume => "assume",
    };

    let prefix = if has_rst_n {
        format!("  always @(posedge {clock}) begin\n    if (rst_n) begin\n      {prop_name}: {sva_keyword}(")
    } else {
        format!("  always @(posedge {clock}) begin\n    {prop_name}: {sva_keyword}(")
    };
    let suffix = if has_rst_n { ");\n    end\n  end\n\n" } else { ");\n  end\n\n" };

    match &prop.formula {
        PropertyFormula::Always(_) => {
            let sv_expr = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            out.push_str(&format!("{prefix}{sv_expr}{suffix}"));
        }
        PropertyFormula::Never(_) => {
            let sv_expr = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            out.push_str(&format!("{prefix}!({sv_expr}){suffix}"));
        }
        PropertyFormula::AlwaysImplies { .. } => {
            let ante_sv = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            let cons_sv = super::emit_expr_inline(prop.formula_exprs[1], registry, sync_map);
            out.push_str(&format!("{prefix}(!({ante_sv})) || ({cons_sv}){suffix}"));
        }
        PropertyFormula::NeverImplies { .. } => {
            let ante_sv = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            let cons_sv = super::emit_expr_inline(prop.formula_exprs[1], registry, sync_map);
            out.push_str(&format!("{prefix}(!({ante_sv})) || (!({cons_sv})){suffix}"));
        }
        PropertyFormula::EventuallyWithin { expr: _, cycles } => {
            let sv_expr = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            out.push_str(&format!("  reg [31:0] prop_{prop_name}_timer;\n"));
            out.push_str(&format!("  always @(posedge {clock}) begin\n"));
            if has_rst_n {
                out.push_str(&format!("    if (!rst_n) prop_{prop_name}_timer <= 0;\n"));
                out.push_str(&format!("    else if ({sv_expr}) prop_{prop_name}_timer <= 0;\n"));
                out.push_str(&format!(
                    "    else prop_{prop_name}_timer <= prop_{prop_name}_timer + 1;\n"
                ));
            } else {
                out.push_str(&format!("    if ({sv_expr}) prop_{prop_name}_timer <= 0;\n"));
                out.push_str(&format!(
                    "    else prop_{prop_name}_timer <= prop_{prop_name}_timer + 1;\n"
                ));
            }
            out.push_str("  end\n");
            out.push_str(&format!("{prefix}prop_{prop_name}_timer < {cycles}{suffix}"));
        }
        PropertyFormula::AlwaysFollowedBy { trigger: _, response: _, delay_cycles } => {
            let trig_sv = super::emit_expr_inline(prop.formula_exprs[0], registry, sync_map);
            let resp_sv = super::emit_expr_inline(prop.formula_exprs[1], registry, sync_map);

            if *delay_cycles == 0 {
                out.push_str(&format!("{prefix}(!({trig_sv})) || ({resp_sv}){suffix}"));
            } else if *delay_cycles == 1 {
                out.push_str(&format!("  reg prop_{prop_name}_trig_d1;\n"));
                out.push_str(&format!("  always @(posedge {clock}) begin\n"));
                if has_rst_n {
                    out.push_str(&format!("    if (!rst_n) prop_{prop_name}_trig_d1 <= 0;\n"));
                    out.push_str(&format!("    else prop_{prop_name}_trig_d1 <= {trig_sv};\n"));
                } else {
                    out.push_str(&format!("    prop_{prop_name}_trig_d1 <= {trig_sv};\n"));
                }
                out.push_str("  end\n");
                out.push_str(&format!(
                    "{prefix}(!(prop_{prop_name}_trig_d1)) || ({resp_sv}){suffix}"
                ));
            } else {
                let msb = delay_cycles - 1;
                out.push_str(&format!("  reg [{msb}:0] prop_{prop_name}_trig_shift;\n"));
                out.push_str(&format!("  always @(posedge {clock}) begin\n"));
                let shift_expr = if *delay_cycles == 2 {
                    format!("{{prop_{prop_name}_trig_shift[0], {trig_sv}}}")
                } else {
                    format!("{{prop_{prop_name}_trig_shift[{}:0], {trig_sv}}}", msb - 1)
                };
                if has_rst_n {
                    out.push_str(&format!("    if (!rst_n) prop_{prop_name}_trig_shift <= 0;\n"));
                    out.push_str(&format!(
                        "    else prop_{prop_name}_trig_shift <= {shift_expr};\n"
                    ));
                } else {
                    out.push_str(&format!("    prop_{prop_name}_trig_shift <= {shift_expr};\n"));
                }
                out.push_str("  end\n");
                out.push_str(&format!(
                    "{prefix}(!(prop_{prop_name}_trig_shift[{msb}])) || ({resp_sv}){suffix}"
                ));
            }
        }
    }
}

