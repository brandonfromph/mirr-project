/// Emit 2-stage (or N-stage) synchronizer chains for all input signals
/// except `clk` and `rst_n`. Returns a mapping of original signal names
/// to their synchronized versions (_s suffix).
pub fn emit_synchronizer_chains(
    registry: &crate::ecs::Registry,
    top_module_id: Option<crate::ecs::EntityId>,
    sync_stages: u32,
    out: &mut String,
) -> Vec<(String, String)> {
    if sync_stages == 0 {
        return Vec::new();
    }
    let stages = sync_stages.min(MAX_SYNC_STAGES);

    let mut mappings = Vec::new();
    out.push_str("  // ── Input Synchronizer Chains ──\n\n");

    for i in 0..registry.names.len() {
        if let (Some(nc), Some(kind_comp), Some(type_comp)) =
            (registry.names[i], &registry.kinds[i], &registry.types[i])
        {
            if let crate::ecs::EntityKind::SIGNAL(SignalKind::Input) = kind_comp.0 {
                // Skip if not belonging to top_module_id
                if let Some(top_id) = top_module_id {
                    if let Some(crate::ecs::components::ModuleComponent(sig_mod_id)) =
                        &registry.modules[i]
                    {
                        if *sig_mod_id != top_id {
                            continue;
                        }
                    }
                }

                let name = registry.resolve_name(nc.0);
                if name == "clk" || name == "rst_n" {
                    continue;
                }

                let width = type_comp.0.signal_type().width();
                let sync_name = format!("{}_s", name);
                let sync_reg = format!("{}_sync", name);

                let mut clock_domain = "clk";
                if let Some(cd) = type_comp.0.annotations.clock_domain.as_deref() {
                    clock_domain = cd;
                }

                // Declare synchronizer register chain.
                let total_bits = width * stages;
                out.push_str(&format!(
                    "  // {}-stage synchronizer for {} (@{clock_domain})\n",
                    stages, name
                ));
                out.push_str(&format!(
                    "  logic [{}:0] {};\n",
                    total_bits.saturating_sub(1),
                    sync_reg,
                ));
                out.push_str("  initial begin\n");
                out.push_str(&format!("    {} = '0;\n", sync_reg));
                out.push_str("  end\n");

                // Sequential synchronizer logic.
                out.push_str(&format!(
                    "  always_ff @(posedge {clock_domain} or negedge rst_n) begin\n"
                ));
                out.push_str(&format!("    if (!rst_n)\n      {} <= '0;\n", sync_reg));
                if stages == 1 {
                    out.push_str(&format!("    else\n      {} <= {};\n", sync_reg, name));
                } else {
                    // Shift chain: {input, sync[high:width]}
                    out.push_str(&format!(
                        "    else\n      {} <= {{{}, {}[{}:{}]}};\n",
                        sync_reg,
                        name,
                        sync_reg,
                        total_bits.saturating_sub(1),
                        width,
                    ));
                }
                out.push_str("  end\n");

                // Output: synchronized signal is the last stage.
                let type_str = super::super::sv_type(&type_comp.0.signal_type());
                out.push_str(&format!(
                    "  {} {} = {}[{}:0];\n\n",
                    type_str,
                    sync_name,
                    sync_reg,
                    width.saturating_sub(1),
                ));

                mappings.push((name.to_string(), sync_name));
            }
        }
    }

    mappings
}

/// Emit only the SVA assertion block (no module wrapper).
///
/// Used by `--emit sva` standalone mode.
pub fn emit_sva_only(result: &PipelineResult) -> String {
    let Some(registry) = result.ecs_registry.as_ref() else {
        return "// [MIRR COMPILER ERROR] ECS registry is missing. Cannot generate SVA assertions.".to_string();
    };
    let module_name = registry.get_module_name().unwrap_or_else(|| "unnamed".to_string());
    let ft = &result.file_table;
    let mut out = String::with_capacity(1024);

    out.push_str("// Auto-generated SVA assertions from MIRR compiler\n");
    out.push_str(&format!("// Module: {}\n\n", module_name));

    let has_rst_n = module_has_rst_n(registry);

    let empty_map = std::collections::HashMap::new();
    emit_property_assertions(registry, has_rst_n, &empty_map, ft, &mut out);

    out
}
