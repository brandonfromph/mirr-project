//! RTL emitter for the MAPE-K autonomic feedback loop.
//!
//! Generates six synthesis-clean SystemVerilog modules:
//!
//! | Module              | Role                                       |
//! |---------------------|--------------------------------------------|
//! | `mirr_monitor`      | Shadow registers, trace buffer, thresholds |
//! | `mirr_analyze`      | Per-property LTL checkers, priority encode |
//! | `mirr_plan`         | Action lookup, priority selection          |
//! | `mirr_execute`      | Action dispatch, emergency latch           |
//! | `mirr_knowledge`    | FIFO ring buffer for adaptation records    |
//! | `mirr_mape_k_top`   | Top-level wiring of all five blocks        |
//!
//! All generated RTL uses `always_ff` / `always_comb` (no `$display`),
//! so the output is synthesis-clean for FPGA / ASIC flows.

#![forbid(unsafe_code)]

mod lower;
mod upper;

use crate::mape_k::bridge::bridge_from_pipeline;
use crate::pipeline::PipelineResult;

// ---------------------------------------------------------------------------
// Constants — bounded resource limits (NASA P10)
// ---------------------------------------------------------------------------

/// Maximum sensor signals in the generated RTL.
pub const MAX_RTL_SIGNALS: usize = 64;

/// Maximum temporal properties in the generated RTL.
pub const MAX_RTL_PROPERTIES: usize = 32;

/// Maximum action-table entries in the generated RTL.
pub const MAX_RTL_ACTIONS: usize = 32;

/// Maximum knowledge FIFO depth in the generated RTL.
pub const MAX_RTL_KNOWLEDGE_DEPTH: usize = 256;

// ---------------------------------------------------------------------------
// Public entry point
// ---------------------------------------------------------------------------

/// Emit the complete MAPE-K RTL (six SystemVerilog modules) from a
/// `PipelineResult`.
///
/// 1. Bridges the pipeline AST into a `SimConfig`.
/// 2. Validates that the config fits within RTL resource limits.
/// 3. Concatenates all six module outputs into a single SV string.
pub fn emit_mape_k_rtl(result: &PipelineResult) -> Result<String, String> {
    let config = bridge_from_pipeline(result).map_err(|errs| {
        let mut msg = String::from("MAPE-K bridge errors:\n");
        for (i, e) in errs.iter().enumerate().take(MAX_RTL_PROPERTIES) {
            msg.push_str(&format!("  [{i}] {e}\n"));
        }
        msg
    })?;

    if config.sensors.len() > MAX_RTL_SIGNALS {
        return Err(format!(
            "too many signals for RTL: {} > {MAX_RTL_SIGNALS}",
            config.sensors.len()
        ));
    }
    if config.properties.len() > MAX_RTL_PROPERTIES {
        return Err(format!(
            "too many properties for RTL: {} > {MAX_RTL_PROPERTIES}",
            config.properties.len()
        ));
    }
    if config.action_table.len() > MAX_RTL_ACTIONS {
        return Err(format!(
            "too many actions for RTL: {} > {MAX_RTL_ACTIONS}",
            config.action_table.len()
        ));
    }

    let mut main_clock = "clk".to_string();
    if let Some(registry) = &result.ecs_registry {
        for ty in registry.types.iter().flatten() {
            if let Some(cd) = &ty.0.annotations.clock_domain {
                main_clock = cd.clone();
                break;
            }
        }
    }

    let mut out = String::with_capacity(8192);
    out.push_str("// =============================================================\n");
    out.push_str("// MAPE-K RTL — auto-generated by MIRR compiler\n");
    out.push_str("// Do not edit — regenerate from .mirr source.\n");
    out.push_str("// =============================================================\n\n");

    out.push_str(&lower::emit_monitor_block(&config, &main_clock));
    out.push_str(&lower::emit_analyze_block(&config, &main_clock));
    out.push_str(&upper::emit_plan_block(&config, &main_clock));
    out.push_str(&upper::emit_execute_block(&config, &main_clock));
    out.push_str(&upper::emit_knowledge_block(&config, &main_clock));
    out.push_str(&upper::emit_mape_k_top(&config, &main_clock));

    Ok(out)
}

