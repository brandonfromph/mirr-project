#[cfg(test)]
mod tests {
    use super::lower::{bit_width, emit_analyze_block, emit_monitor_block, predicate_to_sv};
    use super::upper::{
        emit_execute_block, emit_knowledge_block, emit_mape_k_top, emit_plan_block,
    };
    use crate::mape_k::ltl::{SignalPredicate, TemporalProperty};
    use crate::mape_k::planner::{ActionEntry, AdaptationAction, TriggerCondition};
    use crate::mape_k::sensor::SensorConfig;
    use crate::mape_k::SimConfig;

    fn stub_config() -> SimConfig {
        SimConfig {
            sensors: vec![
                SensorConfig {
                    name: "pressure".to_string(),
                    base_value: 50,
                    noise_amplitude: 2,
                    fault_at_tick: None,
                    fault_value: 0,
                    fault_end_tick: None,
                    seed: 1,
                    is_observable: true,
                },
                SensorConfig {
                    name: "temp".to_string(),
                    base_value: 37,
                    noise_amplitude: 1,
                    fault_at_tick: None,
                    fault_value: 0,
                    fault_end_tick: None,
                    seed: 2,
                    is_observable: true,
                },
            ],
            properties: vec![
                TemporalProperty::Always(SignalPredicate::LessThan("pressure".to_string(), 100)),
                TemporalProperty::EventuallyWithin(SignalPredicate::IsTrue("temp".to_string()), 8),
            ],
            action_table: vec![
                ActionEntry {
                    trigger_property_idx: 0,
                    action: AdaptationAction::EmergencyStop,
                    priority: 255,
                    trigger_on: TriggerCondition::OnViolation,
                },
                ActionEntry {
                    trigger_property_idx: 1,
                    action: AdaptationAction::SetSignal { name: "temp".to_string(), value: 37 },
                    priority: 100,
                    trigger_on: TriggerCondition::OnViolation,
                },
            ],
            window_size: 64,
            knowledge_capacity: 128,
        }
    }

    #[test]
    fn bit_width_values() {
        assert_eq!(bit_width(0), 1);
        assert_eq!(bit_width(1), 1);
        assert_eq!(bit_width(2), 1);
        assert_eq!(bit_width(3), 2);
        assert_eq!(bit_width(4), 2);
        assert_eq!(bit_width(5), 3);
        assert_eq!(bit_width(64), 6);
        assert_eq!(bit_width(256), 8);
    }

    #[test]
    fn predicate_to_sv_is_true() {
        let p = SignalPredicate::IsTrue("x".to_string());
        assert_eq!(predicate_to_sv(&p, "s[0]"), "(s[0] != 32'd0)");
    }

    #[test]
    fn predicate_to_sv_less_than() {
        let p = SignalPredicate::LessThan("x".to_string(), 42);
        assert_eq!(predicate_to_sv(&p, "sig"), "(sig < 32'd42)");
    }

    #[test]
    fn predicate_to_sv_greater_than() {
        let p = SignalPredicate::GreaterThan("x".to_string(), 10);
        assert_eq!(predicate_to_sv(&p, "sig"), "(sig > 32'd10)");
    }

    #[test]
    fn predicate_to_sv_in_range() {
        let p = SignalPredicate::InRange("x".to_string(), 5, 15);
        let sv = predicate_to_sv(&p, "d");
        assert!(sv.contains("d >= 32'd5"));
        assert!(sv.contains("d <= 32'd15"));
    }

    #[test]
    fn monitor_block_contains_shadow_regs() {
        let config = stub_config();
        let sv = emit_monitor_block(&config, "clk");
        assert!(sv.contains("module mirr_monitor"));
        assert!(sv.contains("shadow"));
        assert!(sv.contains("trace_buf"));
        assert!(sv.contains("always_ff"));
        assert!(sv.contains("rst_n"));
    }

    #[test]
    fn analyze_block_contains_property_checkers() {
        let config = stub_config();
        let sv = emit_analyze_block(&config, "clk");
        assert!(sv.contains("module mirr_analyze"));
        assert!(sv.contains("violation_vec"));
        assert!(sv.contains("Property 0: Always"));
        assert!(sv.contains("Property 1: EventuallyWithin"));
        assert!(sv.contains("ev_cnt_1"));
    }

    #[test]
    fn plan_block_contains_action_selection() {
        let config = stub_config();
        let sv = emit_plan_block(&config, "clk");
        assert!(sv.contains("module mirr_plan"));
        assert!(sv.contains("best_priority"));
        assert!(sv.contains("selected_action_idx"));
        assert!(sv.contains("action_valid"));
    }

    #[test]
    fn execute_block_contains_emergency_latch() {
        let config = stub_config();
        let sv = emit_execute_block(&config, "clk");
        assert!(sv.contains("module mirr_execute"));
        assert!(sv.contains("emergency_active"));
        assert!(sv.contains("override_en"));
    }

    #[test]
    fn knowledge_block_contains_fifo() {
        let config = stub_config();
        let sv = emit_knowledge_block(&config, "clk");
        assert!(sv.contains("module mirr_knowledge"));
        assert!(sv.contains("fifo"));
        assert!(sv.contains("wr_ptr"));
        assert!(sv.contains("full"));
    }

    #[test]
    fn top_block_wires_all_submodules() {
        let config = stub_config();
        let sv = emit_mape_k_top(&config, "clk");
        std::fs::write("mape_k_dump.sv", &sv).unwrap();
        assert!(sv.contains("module mirr_mape_k_top"));
        assert!(sv.contains("u_monitor"));
        assert!(sv.contains("u_analyze"));
        assert!(sv.contains("u_plan"));
        assert!(sv.contains("u_execute"));
        assert!(sv.contains("u_knowledge"));
        assert!(sv.contains("tick_counter"));
    }

    #[test]
    fn no_display_in_output() {
        let config = stub_config();
        let mon = emit_monitor_block(&config, "clk");
        let ana = emit_analyze_block(&config, "clk");
        let pln = emit_plan_block(&config, "clk");
        let exe = emit_execute_block(&config, "clk");
        let knw = emit_knowledge_block(&config, "clk");
        let top = emit_mape_k_top(&config, "clk");
        for block in [&mon, &ana, &pln, &exe, &knw, &top] {
            assert!(!block.contains("$display"), "synthesis-clean: no $display");
        }
    }
}
